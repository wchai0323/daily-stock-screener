def sector_of(sic):
    if sic is None:
        return None
    for lo, hi, name in _RANGES:
        if lo <= sic <= hi:
            return name
    return "기타"


def industry_of(sic_desc):
    """SEC 원문(대문자)을 읽기 좋게: 'SEMICONDUCTORS & RELATED DEVICES' → 'Semiconductors & Related Devices'."""
    if not sic_desc:
        return None
    small = {"and", "of", "for", "in", "on", "or", "the", "to", "nec"}
    words = sic_desc.strip().lower().split()
    out = []
    for i, w in enumerate(words):
        if w == "nec":
            out.append("NEC")
        elif i and w in small:
            out.append(w)
        else:
            out.append(w[:1].upper() + w[1:])
    return " ".join(out)
